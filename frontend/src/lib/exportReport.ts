/**
 * Export utilities — generate PDF (print) or DOCX from AppState
 */
import {
  Document, Packer, Paragraph, TextRun, HeadingLevel,
  Table, TableRow, TableCell, WidthType, BorderStyle,
  AlignmentType,
} from 'docx'
import type { AppState } from '../types'

// ── helpers ───────────────────────────────────────────────────────────────────

function h1(text: string) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text, bold: true, size: 28 })] })
}
function h2(text: string) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text, bold: true, size: 24 })] })
}
function h3(text: string) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun({ text, bold: true, size: 22 })] })
}
function para(text: string, opts?: { bold?: boolean; italic?: boolean; color?: string }) {
  return new Paragraph({
    children: [new TextRun({ text, bold: opts?.bold, italics: opts?.italic, color: opts?.color })],
    spacing: { after: 120 },
  })
}
function bullet(text: string) {
  return new Paragraph({
    bullet: { level: 0 },
    children: [new TextRun({ text })],
    spacing: { after: 80 },
  })
}
function spacer() {
  return new Paragraph({ children: [new TextRun({ text: '' })], spacing: { after: 160 } })
}
function divider() {
  return new Paragraph({
    border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC', space: 4 } },
    children: [],
    spacing: { after: 200 },
  })
}

function makeTable(headers: string[], rows: string[][]): Table {
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map(h =>
      new TableCell({
        shading: { fill: '1c1c1e' },
        children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, color: 'FFFFFF', size: 18 })] })],
        width: { size: Math.floor(9000 / headers.length), type: WidthType.DXA },
      })
    ),
  })

  const dataRows = rows.map(row =>
    new TableRow({
      children: row.map(cell =>
        new TableCell({
          children: [new Paragraph({ children: [new TextRun({ text: cell ?? '', size: 18 })] })],
          width: { size: Math.floor(9000 / headers.length), type: WidthType.DXA },
        })
      ),
    })
  )

  return new Table({
    width: { size: 9000, type: WidthType.DXA },
    rows: [headerRow, ...dataRows],
  })
}

// ── Main export function ──────────────────────────────────────────────────────

export async function exportAsDocx(state: AppState): Promise<void> {
  const title = state.sessionTitle || 'Research Report'
  const sections: (Paragraph | Table)[] = []

  // ── Cover ────────────────────────────────────────────────────────────────────
  sections.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text: title, bold: true, size: 40 })],
      spacing: { before: 1000, after: 400 },
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text: `Generated by ResearchAI  •  ${new Date().toLocaleDateString()}`, color: '888888', size: 20 })],
      spacing: { after: 1000 },
    }),
    divider(),
  )

  // ── 1. Research Profile ───────────────────────────────────────────────────
  sections.push(h1('1. Research Profile'), spacer())
  const { domain, population, focus, method, reviewType } = state.profile
  const profileFields = [
    ['Domain', domain], ['Population', population], ['Focus', focus],
    ['Method', method], ['Review Type', reviewType],
  ]
  sections.push(makeTable(['Field', 'Value'], profileFields.filter(([, v]) => v)), spacer(), divider())

  // ── 2. Topics ────────────────────────────────────────────────────────────
  const selectedTopics = state.topics.filter(t => t.selected)
  if (selectedTopics.length > 0) {
    sections.push(h1('2. Selected Research Topics'), spacer())
    for (const topic of selectedTopics) {
      sections.push(
        h3(topic.title),
        para(topic.description, { italic: true }),
        ...(topic.tags.length > 0 ? [para(`Tags: ${topic.tags.join(', ')}`, { color: '555555' })] : []),
        spacer(),
      )
    }
    sections.push(divider())
  }

  // ── 3. Search Queries ────────────────────────────────────────────────────
  if (state.queries.length > 0) {
    sections.push(h1('3. Search Queries'), spacer())
    sections.push(makeTable(
      ['#', 'Query', 'Databases', 'Priority'],
      state.queries.map(q => [
        String(q.queryN),
        q.text,
        (q.databases ?? []).join(', '),
        q.priority,
      ]),
    ), spacer(), divider())
  }

  // ── 4. Included Papers ───────────────────────────────────────────────────
  const included = state.reviewList.filter(r => r.status === 'included' || r.status === 'maybe')
  if (included.length > 0) {
    sections.push(h1('4. Included Papers'), spacer())
    sections.push(makeTable(
      ['Title', 'Authors', 'Year', 'Source', 'Status'],
      included.map(p => [p.title, p.authors, String(p.year), p.source, p.status ?? '']),
    ), spacer(), divider())
  }

  // ── 5. Literature Matrix ─────────────────────────────────────────────────
  if (state.matrixRows.length > 0 && state.matrixColumns.length > 0) {
    sections.push(h1('5. Literature Matrix'), spacer())
    const headers = ['Paper', 'Year', ...state.matrixColumns]
    const rows = state.matrixRows.map(row => [
      row.title,
      String(row.year),
      ...state.matrixColumns.map(col => row.cells[col]?.value ?? '—'),
    ])
    sections.push(makeTable(headers, rows), spacer(), divider())
  }

  // ── 6. Synthesis ─────────────────────────────────────────────────────────
  if (state.themes.length > 0) {
    sections.push(h1('6. Synthesis'), spacer())
    for (const theme of state.themes) {
      sections.push(h2(theme.name))
      sections.push(para(
        `Coverage: ${theme.coverageLabel}  •  Papers: ${theme.paperCount}/${theme.totalPapers}`,
        { color: '666666', italic: true },
      ))
      for (const block of theme.blocks) {
        sections.push(h3(block.title), para(block.content), spacer())
      }
      sections.push(spacer())
    }
    sections.push(divider())
  }

  // ── 7. Gap Analysis ──────────────────────────────────────────────────────
  const selectedGaps = state.gaps.filter(g => g.selected)
  if (selectedGaps.length > 0 || state.gapStatement) {
    sections.push(h1('7. Gap Analysis & Research Statement'), spacer())
    if (state.gapStatement) {
      sections.push(h2('Gap Statement'), para(state.gapStatement), spacer())
    }
    if (selectedGaps.length > 0) {
      sections.push(h2('Identified Gaps'))
      for (const gap of selectedGaps) {
        sections.push(bullet(`${gap.label}: ${gap.description}`))
      }
      sections.push(spacer())
    }
    sections.push(divider())
  }

  // ── 8. Research Questions ────────────────────────────────────────────────
  if (state.rqOptions.length > 0) {
    sections.push(h1('8. Research Questions'), spacer())
    for (const rq of state.rqOptions) {
      const selected = rq.id === state.selectedRQId
      sections.push(
        para(`[${rq.format.toUpperCase()}] ${rq.label}${selected ? '  ✓ Selected' : ''}`, { bold: selected }),
        para(rq.text, { italic: true, color: '333333' }),
        spacer(),
      )
    }
    sections.push(divider())
  }

  // ── 9. Study Design ──────────────────────────────────────────────────────
  const selectedDesign = state.studyDesignOptions.find(d => d.id === state.selectedStudyDesignId)
  if (selectedDesign) {
    sections.push(h1('9. Recommended Study Design'), spacer())
    sections.push(
      para(selectedDesign.name, { bold: true }),
      para(selectedDesign.hint, { italic: true }),
    )
  }

  // ── 10. Final Topic & Paper Structure ────────────────────────────────────
  const finalTopic = state.finalTopicOptions.find(t => t.id === state.selectedFinalTopicId)
  const finalData = state.topicFinalData.find(d => d.topicId === state.selectedFinalTopicId)
  const paperSections = finalData?.paperSections ?? []
  if (finalTopic || paperSections.length > 0) {
    sections.push(h1('10. Final Research Topic & Paper Structure'), spacer())
    if (finalTopic) {
      sections.push(para(finalTopic.title, { bold: true }))
      if (finalTopic.description) sections.push(para(finalTopic.description))
      sections.push(spacer())
    }
    for (const s of paperSections) {
      sections.push(h2(`${s.number}. ${s.name}`))
      if (s.purpose) sections.push(para(s.purpose, { italic: true }))
      if (s.subsections && s.subsections.length > 0) {
        for (const sub of s.subsections) {
          sections.push(h3(sub.title))
          if (sub.content) sections.push(para(sub.content))
        }
      } else {
        for (const b of s.bullets) sections.push(bullet(b))
      }
      sections.push(spacer())
    }
  }

  // ── Build document ───────────────────────────────────────────────────────
  const doc = new Document({
    creator: 'ResearchAI',
    title,
    description: 'Research report generated by ResearchAI',
    sections: [{
      properties: {},
      children: sections,
    }],
  })

  const blob = await Packer.toBlob(doc)
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${title.replace(/[^a-z0-9]/gi, '_')}.docx`
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 10_000)
}

// ── PDF export via browser print ─────────────────────────────────────────────

export function exportAsPdf(state: AppState): void {
  const title = state.sessionTitle || 'Research Report'
  const { domain, population, focus, method, reviewType } = state.profile

  const selectedTopics = state.topics.filter(t => t.selected)
  const included = state.reviewList.filter(r => r.status === 'included' || r.status === 'maybe')
  const selectedGaps = state.gaps.filter(g => g.selected)
  const selectedRQ = state.rqOptions.find(r => r.id === state.selectedRQId)
  const selectedDesign = state.studyDesignOptions.find(d => d.id === state.selectedStudyDesignId)
  const finalTopic = state.finalTopicOptions.find(t => t.id === state.selectedFinalTopicId)
  const paperSections = (state.topicFinalData.find(d => d.topicId === state.selectedFinalTopicId)?.paperSections) ?? []

  const section = (heading: string, content: string) =>
    `<h2 style="margin:20px 0 6px;font-size:13px;font-weight:700;border-bottom:1px solid #ddd;padding-bottom:4px;color:#111">${heading}</h2>${content}`

  const profileRows = [
    ['Domain', domain], ['Population', population], ['Focus', focus],
    ['Method', method], ['Review Type', reviewType],
  ].filter(([, v]) => v).map(([k, v]) =>
    `<tr><td style="font-weight:600;width:120px;padding:3px 6px;color:#555">${k}</td><td style="padding:3px 6px">${v}</td></tr>`
  ).join('')

  const matrixTable = (state.matrixRows.length > 0 && state.matrixColumns.length > 0) ? (() => {
    const ths = ['Paper', 'Year', ...state.matrixColumns].map(h =>
      `<th style="background:#111;color:#fff;padding:4px 6px;font-size:9px;font-weight:600;text-align:left">${h}</th>`
    ).join('')
    const trs = state.matrixRows.map(row =>
      `<tr><td style="padding:3px 6px;font-size:9px;border-bottom:1px solid #eee">${row.title}</td><td style="padding:3px 6px;font-size:9px;border-bottom:1px solid #eee">${row.year}</td>${state.matrixColumns.map(col => `<td style="padding:3px 6px;font-size:9px;border-bottom:1px solid #eee">${row.cells[col]?.value ?? '—'}</td>`).join('')}</tr>`
    ).join('')
    return `<table style="width:100%;border-collapse:collapse;font-size:9px"><thead><tr>${ths}</tr></thead><tbody>${trs}</tbody></table>`
  })() : ''

  const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8"/>
<title>${title}</title>
<style>
  body { font-family: 'Helvetica Neue', Arial, sans-serif; font-size: 11px; color: #222; margin: 0; padding: 30px 40px; }
  h1 { font-size: 20px; color: #000; margin: 0 0 4px; }
  h2 { font-size: 13px; font-weight: 700; border-bottom: 1px solid #ddd; padding-bottom: 4px; margin: 20px 0 6px; }
  h3 { font-size: 11px; font-weight: 700; margin: 10px 0 4px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 10px; }
  th { background: #111; color: #fff; padding: 4px 6px; text-align: left; font-size: 9px; }
  td { padding: 3px 6px; border-bottom: 1px solid #eee; vertical-align: top; }
  .tag { display:inline-block; background:#f0f0f0; border-radius:3px; padding:1px 5px; font-size:9px; margin:1px; }
  .subtitle { color: #666; font-size: 10px; margin-bottom: 24px; }
  .gap-item { margin: 4px 0; padding-left: 12px; border-left: 2px solid #ccc; }
  @media print { body { padding: 0; } }
</style>
</head>
<body>
<h1>${title}</h1>
<div class="subtitle">Generated by ResearchAI &nbsp;·&nbsp; ${new Date().toLocaleDateString()}</div>

${section('1. Research Profile', `<table>${profileRows}</table>`)}

${selectedTopics.length > 0 ? section('2. Selected Topics', selectedTopics.map(t =>
  `<h3>${t.title}</h3><p style="margin:2px 0;color:#444;font-style:italic">${t.description}</p>${t.tags.map(tag => `<span class="tag">${tag}</span>`).join('')}`
).join('<br>')) : ''}

${state.queries.length > 0 ? section('3. Search Queries', `<table><thead><tr><th>#</th><th>Query</th><th>Databases</th><th>Priority</th></tr></thead><tbody>${state.queries.map(q =>
  `<tr><td>${q.queryN}</td><td style="font-family:monospace;font-size:9px">${q.text}</td><td>${(q.databases ?? []).join(', ')}</td><td>${q.priority}</td></tr>`
).join('')}</tbody></table>`) : ''}

${included.length > 0 ? section('4. Included Papers', `<table><thead><tr><th>Title</th><th>Authors</th><th>Year</th><th>Source</th><th>Status</th></tr></thead><tbody>${included.map(p =>
  `<tr><td>${p.title}</td><td>${p.authors}</td><td>${p.year}</td><td>${p.source}</td><td>${p.status ?? ''}</td></tr>`
).join('')}</tbody></table>`) : ''}

${matrixTable ? section('5. Literature Matrix', matrixTable) : ''}

${state.themes.length > 0 ? section('6. Synthesis', state.themes.map(theme =>
  `<h3>${theme.name} <span style="font-weight:400;color:#666">(${theme.coverageLabel})</span></h3>${theme.blocks.map(b =>
    `<p><strong>${b.title}</strong><br><span style="color:#333">${b.content}</span></p>`
  ).join('')}`
).join('')) : ''}

${(selectedGaps.length > 0 || state.gapStatement) ? section('7. Gap Analysis', `
  ${state.gapStatement ? `<p><strong>Gap Statement:</strong> ${state.gapStatement}</p>` : ''}
  ${selectedGaps.map(g => `<div class="gap-item"><strong>${g.label}</strong><br>${g.description}</div>`).join('')}
`) : ''}

${selectedRQ ? section('8. Research Question', `
  <p><strong>[${selectedRQ.format.toUpperCase()}] ${selectedRQ.label}</strong></p>
  <p style="font-style:italic;color:#333">${selectedRQ.text}</p>
`) : ''}

${selectedDesign ? section('9. Study Design', `
  <p><strong>${selectedDesign.name}</strong></p>
  <p style="color:#555">${selectedDesign.hint}</p>
`) : ''}

${(finalTopic || paperSections.length > 0) ? section('10. Final Research Topic & Paper Structure', `
  ${finalTopic ? `<p><strong>${finalTopic.title}</strong></p>${finalTopic.description ? `<p style="color:#555">${finalTopic.description}</p>` : ''}` : ''}
  ${paperSections.map(s => `
    <div style="margin-top:10px">
      <p><strong>${s.number}. ${s.name}</strong></p>
      ${s.purpose ? `<p style="font-style:italic;color:#555">${s.purpose}</p>` : ''}
      ${(s.subsections && s.subsections.length > 0)
        ? s.subsections.map(sub => `<p style="margin-left:12px"><strong>${sub.title}</strong><br>${sub.content}</p>`).join('')
        : `<ul>${s.bullets.map(b => `<li>${b}</li>`).join('')}</ul>`}
    </div>`).join('')}
`) : ''}

</body>
</html>`

  const win = window.open('', '_blank')
  if (!win) return
  win.document.write(html)
  win.document.close()
  win.focus()
  win.print()
}
