/**
 * genActionCatalog.ts — build-time codegen.
 *
 * Parses the AppAction union in src/types/index.ts and emits
 * src/lib/generatedActionCatalog.ts containing every action tagged with a
 * trailing `// @chatbot <description>` comment, along with its payload fields.
 *
 * That generated catalog is the single source of truth for:
 *   - the action list sent to the assistant backend (buildActionsSpec)
 *   - runtime validation before an AI-proposed action is dispatched
 *
 * Run: npm run gen:actions
 */
import * as ts from 'typescript'
import * as fs from 'fs'
import * as path from 'path'
import { fileURLToPath } from 'url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TYPES_FILE = path.join(ROOT, 'src/types/index.ts')
const OUT_FILE = path.join(ROOT, 'src/lib/generatedActionCatalog.ts')

interface Field {
  name: string
  tsType: string
  optional: boolean
}
interface Entry {
  type: string
  doc: string
  fields: Field[]
}

function fail(msg: string): never {
  console.error(`[genActionCatalog] ${msg}`)
  process.exit(1)
}

const text = fs.readFileSync(TYPES_FILE, 'utf8')
const source = ts.createSourceFile(TYPES_FILE, text, ts.ScriptTarget.Latest, true)

// Locate `export type AppAction = ... | ... | ...`
let union: ts.UnionTypeNode | undefined
source.forEachChild(node => {
  if (ts.isTypeAliasDeclaration(node) && node.name.text === 'AppAction' && ts.isUnionTypeNode(node.type)) {
    union = node.type
  }
})
if (!union) fail('Could not find an `export type AppAction = A | B | …` union in src/types/index.ts')

const entries: Entry[] = []

for (const member of union.types) {
  if (!ts.isTypeLiteralNode(member)) continue

  // The @chatbot tag is a trailing comment on the same line as the member.
  const trailing = ts.getTrailingCommentRanges(text, member.end) ?? []
  const tag = trailing
    .map(r => text.slice(r.pos, r.end))
    .map(c => /^\/\/\s*@chatbot\s*(.*)$/.exec(c.trim()))
    .find(Boolean)
  if (!tag) continue

  const doc = (tag[1] ?? '').trim()

  let actionType: string | undefined
  const fields: Field[] = []

  for (const prop of member.members) {
    if (!ts.isPropertySignature(prop) || !prop.name || !prop.type) continue
    const name = prop.name.getText(source)
    if (name === 'type') {
      if (ts.isLiteralTypeNode(prop.type) && ts.isStringLiteral(prop.type.literal)) {
        actionType = prop.type.literal.text
      }
      continue
    }
    fields.push({
      name,
      tsType: prop.type.getText(source),
      optional: !!prop.questionToken,
    })
  }

  if (!actionType) fail(`A @chatbot-tagged member has no string literal \`type\` property: ${member.getText(source)}`)
  entries.push({ type: actionType, doc, fields })
}

if (entries.length === 0) fail('No @chatbot-tagged actions found — did the tag format change?')

const banner = `/**
 * AUTO-GENERATED by scripts/genActionCatalog.ts — DO NOT EDIT BY HAND.
 *
 * Source of truth: the \`// @chatbot\` tags on the AppAction union in ../types.
 * Regenerate with: npm run gen:actions
 */
`

const body = `
export interface CatalogField {
  name: string
  tsType: string
  optional: boolean
}

export interface CatalogEntry {
  type: string
  doc: string
  fields: CatalogField[]
}

export const ACTION_CATALOG: CatalogEntry[] = ${JSON.stringify(entries, null, 2)}
`

fs.writeFileSync(OUT_FILE, banner + body)
console.log(`[genActionCatalog] wrote ${entries.length} chatbot actions → ${path.relative(ROOT, OUT_FILE)}`)
for (const e of entries) console.log(`  · ${e.type}(${e.fields.map(f => f.name).join(', ')})`)
